//! Windows x64 (COFF/PE) GAS Intel-syntax emitter.
//!
//! Prints a [`Translation`] as assembly for a Windows-targeting GNU
//! assembler (`x86_64-w64-mingw32-as`):
//!
//! * `.intel_syntax noprefix`
//! * `.globl` for every defined global symbol
//! * a COFF symbol definition (`.def f; .scl 2; .type 32; .endef`) for
//!   every function (`.scl 2` external, `.scl 3` static; type 32 = function)
//! * the sections in their original order, using the COFF section names and
//!   flags from the translation; dropped sections and `.comm` items (already
//!   materialized in `.bss`) are omitted.

use crate::ast::symbol_name;
use crate::compatibility::directives::SectionMapping;
use crate::ir::Item;
use crate::transpiler::Translation;
use std::fmt::Write;

pub fn emit(t: &Translation, source_name: &str) -> String {
    let m = &t.module;
    let mut out = String::new();
    let _ = writeln!(
        out,
        "# Generated by l2w {} from {source_name}\n# Linux x86-64 (System V, ELF) -> Windows x64 (COFF/PE)",
        env!("CARGO_PKG_VERSION")
    );
    let _ = writeln!(out, ".intel_syntax noprefix");

    let globals: Vec<&str> = m
        .symbols
        .iter()
        .filter(|s| s.global && s.is_defined())
        .map(|s| s.name.as_str())
        .collect();
    if !globals.is_empty() {
        out.push('\n');
        for g in &globals {
            let _ = writeln!(out, ".globl {}", symbol_name(g));
        }
    }
    if !m.functions.is_empty() {
        out.push('\n');
        for f in &m.functions {
            let class = if f.global { 2 } else { 3 };
            let _ = writeln!(
                out,
                ".def {}; .scl {class}; .type 32; .endef",
                symbol_name(&f.name)
            );
        }
    }

    let mut current: Option<String> = None;
    for chunk in &m.chunks {
        let SectionMapping::Keep(coff) = &t.sections[chunk.section] else {
            continue;
        };
        if current.as_deref() != Some(coff.name.as_str()) {
            let _ = writeln!(out, "\n{}", coff.directive());
            current = Some(coff.name.clone());
        }
        for item in &m.sections[chunk.section].items[chunk.start..chunk.end] {
            if matches!(item, Item::Common { .. }) {
                continue;
            }
            let _ = writeln!(out, "{item}");
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn emits_coff_listing() {
        let src = ".intel_syntax noprefix\n.section .rodata\nmsg: .asciz \"hi\"\n.text\n.globl f\n.type f, @function\n\
                   f:\n lea rax, [msg]\n ret\n.size f, .-f\n.section .note.GNU-stack,\"\",@progbits\n";
        let p = crate::parser::parse(src);
        let l = crate::ir::lower(&p.program);
        let t = crate::transpiler::transpile(&l.module);
        assert!(!t.has_errors(), "{:#?}", t.diagnostics);
        let out = emit(&t, "t.s");
        for expected in [
            ".intel_syntax noprefix\n",
            "\n.globl f\n",
            ".def __l2w_sysv_f; .scl 3; .type 32; .endef\n.def f; .scl 2; .type 32; .endef\n",
            "\n.section .rdata,\"dr\"\nmsg:\n    .ascii \"hi\\000\"\n",
            "\n.text\n__l2w_sysv_f:\n    lea rax, [rip + msg]\n    ret\nf:\n    push rbp\n",
        ] {
            assert!(out.contains(expected), "missing {expected:?} in:\n{out}");
        }
        assert!(
            !out.contains(".type f, @function") && !out.contains(".size") && !out.contains("note")
        );
    }
}
